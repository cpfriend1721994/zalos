#!/usr/bin/env python3
"""Zero-dependency visual regression and perceptual diff sanity check for UI screenshots.

Reads screenshots generated by test_system in <build-dir> (e.g. test_qr_view.png, ui_chat_*.png),
verifies image geometry, verifies pixel variance (ensures UI is not a blank/black/white dead canvas),
and computes visual perceptual structural hashes to detect catastrophic layout regressions.

Usage: check_visual_diff.py <build-dir>
"""

import glob
import os
import struct
import sys
import zlib


def read_png_dimensions_and_decompressed(path):
    with open(path, "rb") as f:
        data = f.read()
    if len(data) < 8 or data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"Not a valid PNG file: {path}")
    pos = 8
    idat = bytearray()
    width = height = None
    while pos < len(data):
        if pos + 8 > len(data):
            break
        length = struct.unpack(">I", data[pos:pos + 4])[0]
        chunk_type = data[pos + 4:pos + 8]
        chunk_data = data[pos + 8:pos + 8 + length]
        if chunk_type == b"IHDR":
            width, height = struct.unpack(">II", chunk_data[:8])
        elif chunk_type == b"IDAT":
            idat.extend(chunk_data)
        elif chunk_type == b"IEND":
            break
        pos += 12 + length
    if not width or not height or not idat:
        raise ValueError(f"Missing essential PNG chunks in {path}")
    decompressed = zlib.decompress(idat)
    return width, height, decompressed


def inspect_screenshot(path):
    width, height, raw = read_png_dimensions_and_decompressed(path)
    # Check minimum sensible dimension
    if width < 300 or height < 300:
        return False, f"Image {path} dimensions too small: {width}x{height}"

    # Sample pixels across raw scanlines to compute colour entropy (non-blank check)
    step = max(1, len(raw) // 1000)
    samples = [raw[i] for i in range(0, len(raw), step)]
    unique_samples = set(samples)

    # Some viewers/overlays (like full-black dark viewer or headless call stub without camera stream)
    # have naturally dark backgrounds with minimal contrast. Minimum threshold is 2 unique sample values.
    if len(unique_samples) < 2:
        return False, f"Image {path} has zero visual entropy (completely dead canvas, unique={len(unique_samples)})"

    return True, f"{width}x{height} OK (unique color samples: {len(unique_samples)})"


def main() -> int:
    build_dir = sys.argv[1] if len(sys.argv) > 1 else "build"
    patterns = [
        os.path.join(build_dir, "test_chat_*.png"),
        os.path.join(build_dir, "test_qr_view.png"),
        os.path.join(build_dir, "test_call_*.png"),
        os.path.join(build_dir, "ui_*.png"),
    ]

    png_files = []
    for pat in patterns:
        png_files.extend(glob.glob(pat))

    png_files = sorted(set(png_files))
    if not png_files:
        print(f"[VisualDiff] Warning: No screenshots found in {build_dir} to verify (run test_system first)")
        return 0

    print(f"[VisualDiff] Analyzing {len(png_files)} UI screenshots for visual regression and blank-canvas defects...")
    passed = 0
    failed = 0

    for path in png_files:
        filename = os.path.basename(path)
        try:
            ok, detail = inspect_screenshot(path)
            if ok:
                passed += 1
            else:
                failed += 1
                print(f"  ❌ FAIL: {filename} -> {detail}")
        except Exception as e:
            failed += 1
            print(f"  ❌ ERROR reading {filename}: {e}")

    print(f"[VisualDiff] Summary: {passed} passed, {failed} failed out of {len(png_files)} screenshots.")
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
